create table if not exists public.menu_cantidades_diarias (
 id bigint generated by default as identity primary key,
 fecha date not null,
 plato text not null,
 cantidad_estimada integer not null check (cantidad_estimada >= 0),
 agotado boolean not null default false,
 actualizado_en timestamptz not null default now(),
 unique (fecha, plato)
);
alter table public.menu_cantidades_diarias enable row level security;
grant select, insert, update, delete on public.menu_cantidades_diarias to authenticated;
drop policy if exists menu_cantidades_diarias_select on public.menu_cantidades_diarias;
drop policy if exists menu_cantidades_diarias_insert on public.menu_cantidades_diarias;
drop policy if exists menu_cantidades_diarias_update on public.menu_cantidades_diarias;
drop policy if exists menu_cantidades_diarias_delete on public.menu_cantidades_diarias;
create policy menu_cantidades_diarias_select on public.menu_cantidades_diarias for select to authenticated using (true);
create policy menu_cantidades_diarias_insert on public.menu_cantidades_diarias for insert to authenticated with check (true);
create policy menu_cantidades_diarias_update on public.menu_cantidades_diarias for update to authenticated using (true) with check (true);
create policy menu_cantidades_diarias_delete on public.menu_cantidades_diarias for delete to authenticated using (true);

-- Habilitar eventos Realtime para actualización entre dispositivos, sin fallar si ya están publicados.
do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'menu_cantidades_diarias') then
    alter publication supabase_realtime add table public.menu_cantidades_diarias;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'pedidos') then
    alter publication supabase_realtime add table public.pedidos;
  end if;
end $$;
